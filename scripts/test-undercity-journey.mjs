import assert from 'node:assert/strict';
import {createJourney,fixedVictoryId} from './helpers/undercity-journey.mjs';
let serial=0;
function clear(j,floor,participants=j.data.group.ids){
 const id='e'+serial++;
 const plan=j.begin({id,floor,room:1,roomCount:1,participants});
 const result=j.settle({id,victory:true});
 return {id,plan,result};
}
const j=createJourney();j.select(['a','b','c','d']);
for(let f=1;f<=5;f++)clear(j,f);
assert.equal(j.checkpoint(),5);assert.equal(j.restart().activeDungeonFloor,6);
assert.equal(j.data.grants.length,4);
const saved=j.save();const restored=createJourney(saved);
assert.deepEqual(restored.save(),saved);
const repeat=clear(restored,5);assert.equal(repeat.plan.awards.length,0);
assert.equal(restored.settle({id:repeat.id,victory:true}).replay,true);
assert.equal(restored.data.grants.length,4);
restored.select(['a','b','c','novice']);
assert.equal(restored.position().activeDungeonFloor,1);
assert.equal(restored.data.heroes.a.completedFloor,5);
assert.throws(()=>restored.farm(0),/locked/);
const inFight=restored.begin({id:'locked',floor:1,room:1,roomCount:1,participants:['a','novice']});
assert.throws(()=>restored.select(['a']),/combat/);
assert.throws(()=>restored.restart(),/combat/);
restored.settle({id:'locked',victory:true});
for(let f=2;f<=5;f++)clear(restored,f,['a','b','c','novice']);
assert.equal(restored.data.grants.filter(g=>g.heroId==='novice').length,1);
assert.equal(restored.data.grants.length,5);
const wipe=restored.begin({id:'wipe',floor:6,room:1,roomCount:2,participants:['a','b','c','novice']});
assert.equal(restored.settle({id:'wipe',victory:false,wipe:true}).activeDungeonFloor,6);
assert.equal(restored.data.expedition.halted,true);assert.equal(restored.data.expedition.haltReason,'wipe');
const restartsBeforeResume=restored.data.restarts;assert.equal(restored.restart().activeDungeonFloor,6);
assert.equal(restored.data.restarts,restartsBeforeResume+1);assert.equal(restored.data.expedition.halted,false);
assert.equal(restored.data.grants.length,5);
const fresh=createJourney();fresh.select(['one','two']);
for(let f=1;f<=50;f++)clear(fresh,f);
assert(fresh.canFarm());assert.equal(fresh.data.grants.length,20);
fresh.farm(2);
for(let cycle=0;cycle<2;cycle++)for(let floor=21;floor<=30;floor++)clear(fresh,floor);
assert.equal(fresh.data.expedition.loops,2);assert.equal(fresh.position().activeDungeonFloor,21);
assert.equal(fresh.data.grants.length,20);
fresh.begin({id:'farm-wipe',floor:21,room:1,roomCount:1,participants:['one','two']});
assert.equal(fresh.settle({id:'farm-wipe',victory:false,wipe:true}).activeDungeonFloor,21);
assert.equal(fresh.data.expedition.halted,true);assert.equal(fresh.restart().activeDungeonFloor,21);
fresh.select(['one','new']);assert.equal(fresh.data.expedition.mode,'progression');assert.equal(fresh.position().activeDungeonFloor,1);
assert.throws(()=>fresh.begin({id:'skip',floor:10,room:1,roomCount:1,participants:['one','new']}),/Skipped/);
assert.equal(fixedVictoryId(4,1,1),null);assert.equal(fixedVictoryId(5,1,2),null);
const ko=createJourney();ko.select(['tank','mage']);
for(let f=1;f<5;f++)clear(ko,f);
const plan=ko.begin({id:'ko-win',floor:5,room:1,roomCount:1,participants:['tank','mage']});
assert.equal(plan.awards.length,2);
assert.equal(ko.settle({id:'ko-win',victory:true}).awards.length,2,'End-of-fight KO does not remove starting participants');
const missing=createJourney();missing.select(['active','resting']);
clear(missing,1,['active']);
assert.equal(missing.position().activeDungeonFloor,1,'Absent member not granted progress');
assert.equal(missing.data.heroes.resting.completedFloor,0);
console.log('Journey tests passed: milestones, mixed group, KO eligibility, receipts, save/load, fixed-only primes, farm lock, loops and wipes.');

const {createJourneyDriver}=await import('./helpers/undercity-journey-driver.mjs');
